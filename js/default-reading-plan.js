const BOOK_ALIASES = { Psalm: "Psalms" };

// Parses a passage label like "Genesis 1, 2" or "Psalm 119:1-40" or
// "2 & 3 John" or "Philemon" (single-chapter book, no number given) into
// a list of {book, chapter} entries the Bible reader can jump to.
export function parseReadingLabel(label) {
  const trimmed = label.trim();
  if (/^2 & 3 John$/i.test(trimmed)) {
    return [
      { book: "2 John", chapter: 1 },
      { book: "3 John", chapter: 1 },
    ];
  }

  const match = trimmed.match(/^([1-3]?\s?[A-Za-z ]+?)\s*([\d,:\-\s]*)$/);
  if (!match) return [];
  let book = match[1].trim();
  book = BOOK_ALIASES[book] || book;
  const rest = match[2].trim();

  if (!rest) {
    // No chapter number given (e.g. "Philemon", "Jude", "Obadiah") — these
    // are all single-chapter books.
    return [{ book, chapter: 1 }];
  }
  if (rest.includes(":")) {
    // Verse-range within one chapter, e.g. "119:1-40" — just open the chapter.
    const chapter = parseInt(rest.split(":")[0], 10);
    return isNaN(chapter) ? [] : [{ book, chapter }];
  }
  return rest
    .split(",")
    .map((s) => parseInt(s.trim(), 10))
    .filter((n) => !isNaN(n))
    .map((chapter) => ({ book, chapter }));
}

const PLAN_BY_DATE = new Map();
DEFAULT_READING_PLAN_ROWS.forEach(([month, day, r1, r2, r3]) => {
  const key = `${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
  PLAN_BY_DATE.set(key, [r1, r2, r3]);
});

// Returns [reading1, reading2, reading3] for a given Date, falling back to
// Feb 28 for a leap year's Feb 29 (the plan has no entry for it).
export function readingsForDate(date) {
  const month = date.getMonth() + 1;
  const day = date.getDate();
  const key =
    month === 2 && day === 29
      ? "02-28"
      : `${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
  return PLAN_BY_DATE.get(key) || null;
}

export function dateKey(date) {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, "0");
  const d = String(date.getDate()).padStart(2, "0");
  return `${y}-${m}-${d}`;
}
